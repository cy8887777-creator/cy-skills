def git_info() -> tuple[dict[str, dict], str]:
    result = subprocess.run(["git", "log", "--format=%h%x1f%ad%x1f%s", "--date=short"],
                            cwd=SKILL, check=True, text=True, capture_output=True, encoding="utf-8")
    rows = [line.split("\x1f", 2) for line in result.stdout.splitlines()]
    return ({hash_: {"date": date, "subject": subject} for hash_, date, subject in rows}, rows[0][0])


def build() -> None:
    turns, stats = parse_transcript()
    commits, head = git_info()
    for item in ANNOTATIONS:
        matches = [turn for turn in turns if item["needle"] in turn["user"]]
        if len(matches) != 1:
            raise RuntimeError(f"Annotation must match one human turn: {item['needle']!r} ({len(matches)})")
        item["turn"] = matches[0]["id"]
    for question in QUESTIONS:
        unknown_sources = set(question.get("refs", [])) - EXTERNAL_SOURCES.keys()
        if unknown_sources:
            raise RuntimeError(f"Unknown external sources: {unknown_sources}")
        matches = [turn for turn in turns if question["needle"] in turn["user"]]
        if len(matches) != 1:
            raise RuntimeError(f"Question must match one human turn: {question['needle']!r} ({len(matches)})")
        question["turn"] = matches[0]["id"]
        question["stage"] = next(stage["id"] for stage in STAGES
                                  if stage["from"] <= matches[0]["line"] <= stage["to"])
        question["line"] = matches[0]["line"]
    for stage in STAGES:
        stage["count"] = sum(stage["from"] <= turn["line"] <= stage["to"] for turn in turns)
        stage["time"] = next((turn["time"] for turn in turns if stage["from"] <= turn["line"] <= stage["to"]), "")
    for release in RELEASES:
        for commit in release["commits"]:
            if commit not in commits:
                raise RuntimeError(f"Unknown commit {commit}")
            if commits[commit]["date"] != f"2026-{release['date']}":
                raise RuntimeError(f"Date mismatch for {commit}")
    payload = {"turns": turns, "stages": STAGES, "annotations": ANNOTATIONS,
               "decisions": DECISIONS, "releases": RELEASES,
               "qa_groups": QA_GROUPS, "questions": QUESTIONS, "sources": EXTERNAL_SOURCES,
               "stats": stats | {"head": head, "build": datetime.now(CST).strftime("%Y-%m-%d %H:%M")}}
    packed = base64.b64encode(gzip.compress(json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode(), 9)).decode()
    template = (HERE / "template.html").read_text(encoding="utf-8")
    template = template.replace("/*__THEME__*/", (HERE / "theme.css").read_text(encoding="utf-8"))
    template = template.replace("/*__APP__*/", (HERE / "app.js").read_text(encoding="utf-8"))
    template = template.replace("__PAYLOAD__", packed)
    OUTPUT.write_text(template, encoding="utf-8")
    print(f"Built {OUTPUT} ({OUTPUT.stat().st_size / 1024 / 1024:.2f} MiB)")
    print(f"{len(turns)} human turns; {stats['assistant']} AI text blocks; {stats['trace']} trace blocks")


if __name__ == "__main__":
    build()
