def local_time(value: str) -> str:
    if not value:
        return ""
    return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(CST).strftime("%m-%d %H:%M")


def rendered(value: str) -> str:
    return markdown.markdown(html.escape(value), extensions=["tables", "fenced_code", "nl2br"])


def content_text(value: object) -> str:
    if isinstance(value, str):
        return value
    if not isinstance(value, list):
        return ""
    return "\n".join(item.get("text", "") for item in value if isinstance(item, dict) and item.get("type") == "text")


def parse_transcript() -> tuple[list[dict], dict]:
    turns: list[dict] = []
    current: dict | None = None
    stats = {"lines": 0, "human": 0, "assistant": 0, "trace": 0, "queue": 0, "source_end": ""}

    def add_trace(role: str, body: str, line: int, stamp: str) -> None:
        if current is None or not body.strip():
            return
        current["trace"].append({"role": role, "text": body, "line": line, "time": local_time(stamp)})
        stats["trace"] += 1

    with SOURCE.open(encoding="utf-8") as stream:
        for line, raw in enumerate(stream, 1):
            stats["lines"] = line
            try:
                row = json.loads(raw)
            except json.JSONDecodeError:
                continue
            kind = row.get("type")
            stamp = row.get("timestamp", "")
            if stamp:
                stats["source_end"] = local_time(stamp)
            if kind == "queue-operation":
                stats["queue"] += 1
                if row.get("operation") == "remove" and row.get("reason") == "absorbed_mid_turn":
                    add_trace("queue", "消息并入正在执行的回合（原始队列事件；不能据此判定执行被中断）", line, stamp)
                continue
            message = row.get("message") or {}
            parts = message.get("content") or []
            if isinstance(parts, str):
                parts = [{"type": "text", "text": parts}]
            if kind == "user" and (row.get("origin") or {}).get("kind") == "human":
                body = content_text(parts)
                if body.startswith("<ide_opened_file>"):
                    add_trace("context", body, line, stamp)
                    continue
                images = sum(isinstance(part, dict) and part.get("type") == "image" for part in parts)
                if not body.strip() and not images:
                    continue
                current = {"id": f"t{line}", "line": line, "time": local_time(stamp),
                           "timestamp": stamp, "user": body, "images": images,
                           "quoted": line in {7505, 8580, 8855, 9163, 9186, 9214},
                           "reply": [], "trace": [], "reply_lines": []}
                turns.append(current)
                stats["human"] += 1
                continue
            if kind == "assistant" and current is not None:
                for part in parts:
                    if not isinstance(part, dict):
                        continue
                    part_kind = part.get("type")
                    if part_kind == "text" and part.get("text", "").strip():
                        current["reply"].append(part["text"])
                        current["reply_lines"].append(line)
                        stats["assistant"] += 1
                    elif part_kind == "thinking":
                        add_trace("thinking", part.get("thinking", ""), line, stamp)
                    elif part_kind == "tool_use":
                        body = part.get("name", "") + "\n" + json.dumps(part.get("input", {}), ensure_ascii=False, indent=2)
                        add_trace("tool", body, line, stamp)
            elif kind == "user" and current is not None:
                for part in parts:
                    if isinstance(part, dict) and part.get("type") == "tool_result":
                        add_trace("result", content_text(part.get("content")) or "[非文本工具结果]", line, stamp)

    for turn in turns:
        turn["user_html"] = rendered(turn["user"])
        turn["reply_html"] = rendered("\n\n".join(turn["reply"])) if turn["reply"] else ""
        turn["search"] = re.sub(r"\s+", " ", turn["user"] + " " + " ".join(turn["reply"]))[:12000]
        turn["reply_count"] = len(turn["reply"])
        del turn["reply"]
    return turns, stats


